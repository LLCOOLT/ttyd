USER_FUNC(moamoa_bomb) {
    s32 i;
    ExtPose* pose;
    Moamoa* elem;
    s32 n;

    BattleGetUnitPtr(_battleWorkPointer, wp->unitId);
    wp->center = (Vec){0.0f, 0.0f, 0.0f};
    if (isFirstCall) {
        extGetPosePtr();
        elem = wp->elems;
        for (i = 0; i < wp->count; i++, elem++) {
            if (*elem->owner != -1) {
                elem->flags &= ~1;
            }
        }
    }
    if (!(gp->retraceCount & 1)) {
        pose = extGetPosePtr();
        n = 0;
        elem = wp->elems;
        for (i = 0; i < wp->count; i++, pose++, elem++) {
            if (pose->mtx[1][3] >= 0.0f && !(elem->flags & 1)) {
                elem->flags |= 1;
                if (elem->flags & 1) {
                    elem->vel.x = randf(0.0f, 60.0f) - 30.0f;
                    elem->vel.y = randf(0.0f, 35.0f);
                    n++;
                    elem->vel.z = 60.0f + randf(0.0f, 30.0f);
                    elem->pos2.x = pose->mtx[0][3];
                    elem->pos2.y = pose->mtx[1][3];
                    elem->pos2.z = pose->mtx[2][3];
                    if (n >= 10) {
                        break;
                    }
                }
            }
        }
    }
    pose = extGetPosePtr();
    elem = wp->elems;
    for (i = 0; i < wp->count; i++, pose++, elem++) {
        if (elem->flags & 1) {
            if (elem->pos2.y >= -500.0f) {
                elem->pos2.x += elem->vel.x;
                elem->pos2.y += elem->vel.y;
                elem->pos2.z += elem->vel.z;
                elem->vel.y -= 1.0f;
            }
            pose->mtx[0][3] = elem->pos2.x;
            pose->mtx[1][3] = elem->pos2.y;
            pose->mtx[2][3] = elem->pos2.z;
        }
    }
    pose = extGetPosePtr();
    n = 0;
    for (i = 0; i < wp->count; i++, pose++) {
        if (pose->mtx[1][3] >= -200.0f) {
            n++;
        }
    }
    if (n <= 9) {
        wp->center = (Vec){0.0f, -1000.0f, 0.0f};
        return 2;
    }
    return 0;
}
