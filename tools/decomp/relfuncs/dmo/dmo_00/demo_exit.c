void demo_exit(void) {
    CameraEntry* cam = camGetPtr(8);

    if (wp->tpl != NULL) {
        fileFree(wp->tpl);
    }
    psndClearFlag(4);
    cam = camGetPtr(4);
    cam->viewport[0] = 0.0f;
    cam->viewport[1] = 0.0f;
    cam->viewport[2] = 608.0f;
    cam->viewport[3] = 480.0f;
    statusWinDispOn();
}
