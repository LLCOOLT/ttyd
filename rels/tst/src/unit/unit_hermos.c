/**
 * Script helper called every frame: keeps a flame effect on part 2 of the unit,
 * growing it to the unit's size (0.1 per frame).
 * Creates the effect on the first call and blocks until the script is stopped.
 */
static USER_FUNC(eff_fire) {
    s32 id = BattleTransID(event, evtGetValue(event, event->args[0]));
    BattleUnit* unit = BattleGetUnitPtr(_battleWorkPointer, id);
    BattleUnitPart* part = BtlUnit_GetPartsPtr(unit, 2);
    EffFireWork* wk;
    f32 x;
    f32 y;
    f32 z;

    if (isFirstCall) {
#if VERSION <= VERSION_DEMO_JP
        eff = effFireEntry(6, 90, 0.0f, -1000.0f, 0.0f, 1.0f);
#else
        eff = effFireEntry(6, 106, 0.0f, -1000.0f, 0.0f, 1.0f);
#endif
        ((EffFireWork*)eff->userdata)->scaleX = 0.0f;
        ((EffFireWork*)eff->userdata)->scaleY = 0.0f;
    }
    wk = eff->userdata;
    if (wk != NULL) {
        BtlUnit_GetPartsPos(part, &x, &y, &z);
        wk->position = (Vec){x, y, z};
        wk->scaleX += 0.1f * unit->sizeMultiplier;
        if (wk->scaleX >= unit->sizeMultiplier) {
            wk->scaleX = unit->sizeMultiplier;
        }
        wk->scaleY += 0.1f * unit->sizeMultiplier;
        if (wk->scaleY >= unit->sizeMultiplier) {
            wk->scaleY = unit->sizeMultiplier;
        }
    }
    return EVT_RETURN_BLOCK;
}

/**
 * The Ember's fireball (weapon in LW(9)): picks a target (the first-strike target in a first strike) and throws
 * part 2, wrapped in a flame (eff_fire), at it with SFX_ENM_BUBBLE_ATTACK2 and 3; the target dodges or takes the
 * damage with a smoke puff.
 */
